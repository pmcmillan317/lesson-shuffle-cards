import os,hashlib,json
os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'public'))
pages=['/']+['/'+f[:-5] for f in sorted(os.listdir('.')) if f.endswith('.html') and f not in('index.html','404.html')]+['/print/'+f[:-5] for f in sorted(os.listdir('print')) if f.endswith('.html')]
assets=['/print.css?v=1','/style.css','/site.js','/logo.webp?v=2','/favicon.png','/manifest.webmanifest','/icon-192.png','/icon-512.png']+['/fonts/'+f for f in sorted(os.listdir('fonts')) if f.endswith('.woff2')]
imgs=['/cards/'+f for f in sorted(os.listdir('cards'))]
h=hashlib.sha1()
for f in sorted(os.listdir('.'))+['cards/'+x for x in sorted(os.listdir('cards'))]+['print/'+x for x in sorted(os.listdir('print'))]:
    if os.path.isfile(f) and f!='sw.js': h.update(open(f,'rb').read())
ver=h.hexdigest()[:10]
sw=f'''/* Lesson Shuffle offline support. Generated by build_sw.py; version changes when any file changes. */
const V = 'ls-{ver}';
const CORE = {json.dumps(pages+assets)};
const IMGS = {json.dumps(imgs)};
self.addEventListener('install', e => {{
  e.waitUntil(caches.open(V).then(c => c.addAll(CORE).then(() => Promise.all(IMGS.map(u => c.add(u).catch(() => {{}}))))).then(() => self.skipWaiting()));
}});
self.addEventListener('activate', e => {{
  e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k !== V).map(k => caches.delete(k)))).then(() => self.clients.claim()));
}});
self.addEventListener('fetch', e => {{
  const r = e.request; if (r.method !== 'GET') return;
  const u = new URL(r.url); if (u.origin !== location.origin) return;
  if (r.mode === 'navigate') {{
    e.respondWith(fetch(r).then(res => {{ const cp = res.clone(); caches.open(V).then(c => c.put(r, cp)); return res; }})
      .catch(() => caches.match(r, {{ ignoreSearch: true }}).then(m => m || caches.match(u.pathname.replace(/\\.html$/, '')) || caches.match('/'))));
    return;
  }}
  e.respondWith(caches.match(r, {{ ignoreSearch: true }}).then(m => m || fetch(r).then(res => {{ if (res.ok) {{ const cp = res.clone(); caches.open(V).then(c => c.put(r, cp)); }} return res; }})));
}});
'''
open('sw.js','w').write(sw); print('sw',ver,len(pages),'pages',len(imgs),'images')
